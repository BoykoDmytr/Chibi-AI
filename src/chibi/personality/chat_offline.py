"""Offline chat: an honest keyword responder for Phase 1 (no language model).

She recognises a handful of intents in Ukrainian (greetings, "як справи",
"помовч", feeding, petting, the time, ...) and answers with solicited lines
from the phrase bank.  Anything else gets an honest "I only understand simple
phrases until my AI brain arrives" - she never pretends to understand.

How :func:`detect_intent` reads a message:

0. A roleplay action between asterisks ("*гладить по голові*") is the user's
   action towards her and is read first.  A word in quotes is mentioned, not
   said ("Як буде «привіт» японською?"), so it is set aside - unless the quote
   is all the message says ("«Помовч»", copied from her own hint).
1. It is split into clauses at punctuation, and each clause is
   :func:`~chibi.personality.text_uk.normalize`-d (lower case, one kind of
   apostrophe, no punctuation) with letters stretched for emphasis squeezed
   ("привіііт" -> "привіт").
2. The *address* is set aside: her current name and its vocative ("Мія" /
   "Міє", or "Кіра" / "Кіро" after a rename) at either end of the message or as
   a clause of its own, pet names ("сонечко", "дівчинко", "..., люба") and an
   empty opener ("Хм, ...", "Ага, ...").  So "Міє, будь тихо" reads as "будь
   тихо" and "Як ти, сонечко?" as "як ти".  If the shortened message means
   nothing, it is read as written too: "Ти моє сонечко" is a compliment.
3. Intents are tried in a fixed priority order: being asked to be quiet (or to
   talk again) beats everything, an action like feeding beats a greeting.  The
   user's *feeling* ("мені сумно", "я втомився") does not end the search: an
   explicit command in the same message wins ("Мені сумно, розкажи жарт" is a
   joke, "Я втомився, йди спати" puts her to bed), and only a feeling on its own
   (or with a plea for comfort: "мені погано, обійми мене") gets the supportive
   reply.
4. Typos: single words within one edit of a known trigger word ("пирвіт" ->
   "привіт", "дкяую" -> "дякую", and a dropped letter in a short one: "дякю") are
   corrected, and the intent's own patterns run again, so a typo never bypasses
   the context rules below.  Real words that happen to be one edit away ("не
   дякуй", "я відпочину", "мама нагодує") are never "corrected".

Who a message is about matters more than which words it contains: "не мовчи"
asks her to talk, "я хочу їсти" is about the user's lunch while "я приніс
поїсти" is an offer to her, "цей бос тупий" is not an insult to her, "мій
персонаж помер" is a game, and "у мене поганий настрій" is not a question about
hers.  So insults and compliments need to be addressed to her ("ти ...", or the
whole message is the word), actions skip the user's own eating and bedtime, and
the user's own feelings get their own small, supportive replies.  A negated
action is not the action ("не обіймай мене", "не йди спати", "не їж мені
мізки"), and neither is someone else doing it ("мене ніхто не обіймає", "я
помовчу").

Privacy: the user's text is never logged - not even at debug level.  Only the
detected intent name is.
"""

