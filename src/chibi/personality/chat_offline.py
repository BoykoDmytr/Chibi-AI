def _rx(*patterns: str) -> tuple[re.Pattern[str], ...]:
    return tuple(re.compile(p) for p in patterns)


@dataclass(frozen=True)
class Intent:
    name: str
    patterns: tuple[re.Pattern[str], ...]
    #: Single trigger words (>= 5 letters) matched with one typo allowed.
    fuzzy_words: tuple[str, ...] = ()
    #: The intent does not apply when one of these matches: "я хочу їсти" is
    #: about the user's lunch, not a request to feed her.
    exclude: tuple[re.Pattern[str], ...] = ()
    #: For a feeling: the requests that win when they are in the same message
    #: ("мені сумно, розкажи жарт" is a joke).  Empty for everything else.
    yields_to: frozenset[str] = frozenset()

    def matches(self, text: str) -> bool:
        if not any(pattern.search(text) for pattern in self.patterns):
            return False
        return not self.excluded(text)

    def excluded(self, text: str) -> bool:
        return any(pattern.search(text) for pattern in self.exclude)


