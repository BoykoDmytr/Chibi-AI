def _within_one_edit(a: str, b: str) -> bool:
    """Optimal string alignment distance <= 1 (insert, delete, substitute or swap neighbours)."""
    if a == b:
        return True
    la, lb = len(a), len(b)
    if abs(la - lb) > 1:
        return False
    if la == lb:
        diffs = [i for i in range(la) if a[i] != b[i]]
        if len(diffs) == 1:
            return True
        if len(diffs) != 2 or diffs[1] != diffs[0] + 1:
            return False
        i, j = diffs
        return a[i] == b[j] and a[j] == b[i]
    shorter, longer = (a, b) if la < lb else (b, a)
    return any(longer[:i] + longer[i + 1:] == shorter for i in range(len(longer)))


MIN_FUZZY_LENGTH = 5

#: Real words one edit away from a trigger word: never "corrected".  "Не дякуй" is
#: not thanks, "я відпочину" / "я помовчу" / "я замовкну" are the user, "мама нагодує
#: кота", "він поїсть", "це допоможе", "мама тебе вітає" are someone else.
_REAL_WORDS = frozenset({
    "дякуй", "помовчу", "замовкну", "замовкне", "замовкли", "відпочину", "відпочине", "нагодує", "поїсть",
    "погладить", "погладили", "погладжує", "обійме", "допоможе", "вітає", "віта", "вітю", "якую", "справу",
    "справі",
})


def _corrected(words: list[str], triggers: tuple[str, ...]) -> str | None:
    """The message with every word that is one typo away from a trigger replaced by
    that trigger, or None when nothing was corrected.  A word one letter shorter than
    :data:`MIN_FUZZY_LENGTH` counts only with a dropped letter ("дякю" -> "дякую")."""
    changed = False
    out: list[str] = []
    for word in words:
        if word not in triggers and word not in _REAL_WORDS:
            if len(word) >= MIN_FUZZY_LENGTH:
                fix = next((t for t in triggers if _within_one_edit(word, t)), None)
            elif len(word) == MIN_FUZZY_LENGTH - 1:
                fix = next((t for t in triggers if len(t) == len(word) + 1 and _within_one_edit(word, t)),
                           None)
            else:
                fix = None
            if fix is not None:
                word, changed = fix, True
        out.append(word)
    return " ".join(out) if changed else None


def _match(text: str) -> str | None:
    """The first intent in priority order that matches ``text``; a feeling gives way
    to a request in the same message ("мені сумно, розкажи жарт" -> joke)."""
    for intent in INTENTS:
        if intent.matches(text):
            if intent.yields_to:
                request = next((other.name for other in INTENTS
                                if other.name in intent.yields_to and other.matches(text)), None)
                if request is not None:
                    return request
            return intent.name
    return None


def _match_typos(text: str) -> str | None:
    """Correct words towards an intent's trigger words, then apply that intent's own
    patterns, so "ця гра чудвоа" is still not a compliment to her.  The exclusions
    must hold for the text as typed too: correcting "нагодуй мене" (the user wants
    food) to the trigger "нагодую" must not erase what excluded it."""
    words = text.split()
    for intent in INTENTS:
        if intent.fuzzy_words:
            corrected = _corrected(words, intent.fuzzy_words)
            if corrected is not None and intent.matches(corrected) and not intent.excluded(text):
                return intent.name
    return None


#: Roleplay actions ("*гладить по голові*"): the narrated third person is the user
#: acting on her, the very forms the spoken patterns leave out ("мама його гладить").
_ROLEPLAY_INTENTS: tuple[Intent, ...] = (
    Intent("pet", _rx(
        rf"\b({_PET_VERB}|цілує|поцілува\w*|поцілув\w*|чмок\w*)",
    ), exclude=_rx(rf"\bне ({_PET_VERB})")),
    Intent("feed", _rx(
        r"\b(годує|нагодува\w*|погодува\w*)\b",
        rf"\b(дає|дала|дав|простяга\w*|протяга\w*|пригоща\w*|підсува\w*|підсовує|кладе|поклала|поклав|кидає"
        rf"|кинула|кинув)( \w+){{0,2}} ({_FOOD}|печив\w*|цукерк\w*|смаколик\w*|тортик\w*)\b",
    ), exclude=_rx(r"\bне (годує|дає|простяга\w*|пригоща\w*)\b")),
)


def _match_roleplay(text: str) -> str | None:
    """The action narrated between asterisks, if it is one she understands."""
    for action in _ROLEPLAY.findall(text):
        reading = _squeeze(action)
        intent = next((i.name for i in _ROLEPLAY_INTENTS if i.matches(reading)), None)
        if intent is not None:
            return intent
    return None


def detect_intent(text: str, name: str = DEFAULT_NAME) -> str:
    """The intent name for a chat message ("unknown" if nothing matched).

    ``name`` is her current name (``settings.character.name``): the user calls
    her by it ("Кіро, будь тихо") and it is not part of what they ask.
    """
    if (roleplay := _match_roleplay(text)) is not None:
        return roleplay
    names = address_forms(name)
    clauses = _clauses(_unquoted(text, names))
    if not clauses:
        return "unknown"
    as_written = " ".join(word for clause in clauses for word in clause)
    shortened = " ".join(_without_address(clauses, names))
    readings = (shortened, as_written) if shortened != as_written else (as_written,)
    for match in (_match, _match_typos):
        for reading in readings:
            intent = match(reading)
            if intent is not None:
                return intent
    return "unknown"


class OfflineChatResponder:
    def __init__(
        self,
        selector: PhraseSelector,
        reactions: ReactionEngine,
        settings: Callable[[], Settings],
        clock: Clock,
        perform: Callable[[str], str] | None = None,
        needs: Callable[[], Mapping[str, float]] | None = None,
    ) -> None:
        """``perform("feed" | "pet" | "rest")`` runs the tamagotchi interaction
        (without its own announcement) and returns the outcome string;
        ``needs()`` returns the current needs (``Needs.to_dict()``-like, a
        ``"mood"`` entry is used as is) for "як ти себе почуваєш"."""
        self._selector = selector
        self._reactions = reactions
        self._settings = settings
        self._clock = clock
        self._perform = perform
        self._needs = needs
        self._model = NeedsModel()

    def respond(self, text: str) -> ChatReply:
        """Reply to one chat message.  Always returns a reply, never raises."""
        intent = "unknown"
        try:
            intent = detect_intent(text if isinstance(text, str) else "", self._settings().character.name)
            log.debug("chat intent: %s", intent)
            return self._handle(intent)
        except Exception:
            log.exception("offline chat failed for intent %s", intent)
            return ChatReply(text=FALLBACKS["unknown"])

    # -- handlers ------------------------------------------------------------------------------

    def _handle(self, intent: str) -> ChatReply:
        if intent == "quiet_on":
            self._reactions.set_quiet(self._settings().behavior.quiet_minutes)
            return self._reply(intent, INTENT_KEYS[intent], action="quiet_on")
        if intent == "quiet_off":
            self._reactions.clear_quiet()
            return self._reply(intent, INTENT_KEYS[intent], action="quiet_off")
        if intent in ACTIONS:
            return self._action(intent)
        if intent == "time":
            return self._reply(intent, INTENT_KEYS[intent], time=self._time())
        if intent == "mood":
            mood = self._mood_key()
            keys = (f"chat.mood.{mood}", "chat.how_are_you") if mood else ("chat.how_are_you",)
            return self._reply(intent, keys)
        return self._reply(intent, INTENT_KEYS.get(intent, INTENT_KEYS["unknown"]))

    def _action(self, intent: str) -> ChatReply:
        perform_name, reply_action = ACTIONS[intent]
        if self._perform is None:
            return ChatReply(text=FALLBACKS["action_unavailable"])
        try:
            outcome = self._perform(perform_name)
        except Exception:
            log.exception("chat action %s failed", perform_name)
            return ChatReply(text=FALLBACKS["action_unavailable"])
        keys: tuple[str, ...] = ()
        fallback = intent
        if isinstance(outcome, str) and outcome:
            keys = (f"interaction.{perform_name}.{outcome}",)
            if f"{intent}.{outcome}" in FALLBACKS:
                fallback = f"{intent}.{outcome}"
        # A refusal (or an outcome we do not know) did not feed / pet / rest her.
        succeeded = isinstance(outcome, str) and outcome in SUCCESS_OUTCOMES[perform_name]
        return self._reply(intent, keys, action=reply_action if succeeded else "", fallback=fallback)

    def _reply(self, intent: str, keys: tuple[str, ...], action: str = "", fallback: str | None = None,
               **variables: Any) -> ChatReply:
        speech = self._selector.say(*keys, solicited=True, **variables) if keys else None
        if speech is not None:
            return ChatReply(text=speech.text, state=speech.state, portrait=speech.portrait, action=action)
        template = FALLBACKS.get(fallback or intent, FALLBACKS["unknown"])
        values = {"name": self._settings().character.name, "time": variables.get("time") or self._time()}
        return ChatReply(text=template.format_map(values), action=action)

    def _time(self) -> str:
        return format_clock(datetime.fromtimestamp(self._clock.now()))

    def _mood_key(self) -> str | None:
        if self._needs is None:
            return None
        try:
            snapshot: Any = self._needs()
        except Exception:
            log.exception("could not read needs for the chat")
            return None
        if isinstance(snapshot, Mapping):
            mood = snapshot.get("mood")
            data: Mapping[str, Any] = snapshot
        else:  # a view object such as settings.facade.NeedsView
            mood = getattr(snapshot, "mood", None)
            data = {name: getattr(snapshot, name) for name in STAT_NAMES if hasattr(snapshot, name)}
        if not isinstance(mood, str) or not mood.strip():
            mood = self._model.mood(Needs.from_dict(data))
        return MOOD_KEYS.get(mood.strip().capitalize())
