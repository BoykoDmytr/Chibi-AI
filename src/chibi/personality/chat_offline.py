# -- reading a message: clauses, her name, the address ------------------------------------------

_STRETCHED = re.compile(r"(\w)\1{2,}")
# Where one clause ends: the comma in "Міє, тихо" is what makes "Міє" an address.
_CLAUSE_BREAK = re.compile(r"[,.!?;:…—–()\[\]\n]+|\s-+\s")
# A word in quotes is mentioned, not said: "Як буде «привіт» японською?", "Як
# правильно: «дякую» чи «спасибі»?", a game called "Тиша".
_QUOTED = re.compile(r"«[^«»]*»|„[^„“”]*[“”]|“[^“”]*”|\"[^\"]*\"")
# What stands in for a quote: a word no pattern knows, so the words around it do not
# join up ("не «тихо» говори" must not read "не говори").
_QUOTE_STAND_IN = " цитата "
# Words that say nothing next to a quote: "«Помовч», будь ласка" is still the request.
_POLITE = frozenset({"будь", "ласка", "прошу", "пліз", "плиз"})
# A roleplay action: "*гладить по голові*", "*простягає яблучко*".
_ROLEPLAY = re.compile(r"\*([^*\n]+)\*")

#: Pet names she is called by, with or without a comma ("Молодець, дівчинко",
#: "як ти сонечко"): vocative forms, or nouns nobody says as a whole sentence.
_ADDRESS_NOUNS = frozenset({
    "сонечко", "сонце", "дівчинко", "дівчино", "кицю", "кицюню", "котику", "котю", "зайчику", "зайко",
    "золотко", "золотце", "крихітко", "подруго", "подружко", "рибко", "любонько", "серденько", "ластівко",
    "лапочко", "малявко", "пташко", "принцесо", "красуне", "красунечко", "бусинко", "лялечко",
})
#: Adjectives used to call her ("Люба, помовч") also describe things ("ти така
#: мила", "я мала рацію"), so they count only as a clause of their own.
_ADDRESS_ADJECTIVES = frozenset({
    "люба", "мила", "мала", "маленька", "хороша", "дорога", "дорогенька", "рідна", "солоденька", "кохана",
})
#: Words that may come with an address in its own clause: "моя люба", "ну, Міє", "агов, сонечко".
_ADDRESS_FRAME = frozenset({"моя", "мій", "моє", "наша", "наш", "ну", "о", "ой", "ох", "агов", "гей", "ей"})
#: A first clause of one of these words says nothing: "Хм, дай подумати", "Ага, тихо".
_OPENERS = frozenset({
    "ну", "так", "ок", "окей", "ага", "угу", "слухай", "слухайте", "ой", "ох", "ех", "ах", "агов", "гей",
    "ей", "хм", "все", "добре", "гаразд", "ладно", "отже", "короче", "о",
})
_VOWELS = frozenset("аеєиіїоуюяь'")
_CONSONANTS = frozenset("бвгґджзклмнпрстфхцчшщ")


def _squeeze(text: str) -> str:
    """Normalise and squeeze letters stretched for emphasis ("привіііт" -> "привіт")."""
    return _STRETCHED.sub(r"\1", normalize(text))


def _vocatives(word: str) -> set[str]:
    """``word`` and its simple Ukrainian vocatives: "мія" -> "міє" (and the spelling
    "міа"), "кіра" -> "кіро", "таня" -> "таню", "сашко" -> "сашку", "андрій" ->
    "андрію", "ігор" -> "ігоре" / "ігорю"... - generous on purpose: a form is only
    ever dropped from the very edge of a message or as a clause of its own."""
    forms = {word}
    if len(word) < 2:
        return forms
    stem, last = word[:-1], word[-1]
    if last == "я":
        if stem[-1] in _VOWELS:
            forms |= {stem + "є", stem + "а"}  # Мія -> Міє / Міа, Соломія -> Соломіє
        else:
            forms |= {stem + "ю", stem + "е"}  # Таня -> Таню, Ілля -> Ілле
    elif last == "а":
        forms.add(stem + "о")  # Кіра -> Кіро, Мар'яна -> Мар'яно
        if stem[-1] in "жчшщ":
            forms.add(stem + "е")
    elif last == "о":
        forms.add(stem + ("у" if stem.endswith("к") else "е"))  # Сашко -> Сашку, Петро -> Петре
    elif last in "йь":
        forms |= {stem + "ю", stem + "е"}  # Андрій -> Андрію, Василь -> Василю
    elif last in _CONSONANTS:
        forms |= {word + "е", word + "у", word + "ю"}  # Ігор -> Ігоре, Олег -> Олегу
    return forms


@functools.lru_cache(maxsize=32)
def address_forms(name: str) -> frozenset[tuple[str, ...]]:
    """The ways to call her by ``name``: the name and its vocatives, as normalised word tuples.

    ``address_forms("Мія")`` holds ``("мія",)``, ``("міє",)`` and ``("міа",)``.  For a
    name of several words the last one alone counts too ("Міс Кітті" -> "Кітті").
    """
    words = _squeeze(name).split() if isinstance(name, str) else []
    if not words:
        return frozenset()
    options = [sorted(_vocatives(word)) for word in words]
    if len(words) <= 3:
        forms = set(itertools.product(*options))
    else:
        forms = {(*words[:-1], form) for form in options[-1]}
    forms |= {(form,) for form in options[-1]}
    return frozenset(forms)


def _clauses(text: str) -> list[list[str]]:
    """The message as normalised words, grouped into the clauses its punctuation marks."""
    clauses = []
    for part in _CLAUSE_BREAK.split(text):
        words = _squeeze(part).split()
        if words:
            clauses.append(words)
    return clauses


def _unquoted(text: str, names: frozenset[tuple[str, ...]]) -> str:
    """``text`` with every quoted word replaced by a stand-in nobody reacts to, so
    "Як буде «привіт» японською?" is not a greeting.  When the quote is all the
    message says ("«Помовч»", "Міє, «помовч», будь ласка" - copied from her own
    hint), it is kept: then it is the request itself."""
    if not _QUOTED.search(text):
        return text
    rest = _clauses(_QUOTED.sub(",", text))
    if all(_is_address(clause, names)
           or all(word in _OPENERS or word in _ADDRESS_FRAME or word in _POLITE for word in clause)
           for clause in rest):
        return text
    return _QUOTED.sub(_QUOTE_STAND_IN, text)


def _is_address(words: Sequence[str], names: frozenset[tuple[str, ...]]) -> bool:
    """A clause that only calls her: "Міє", "моя люба", "агов, сонечко"."""
    start, end = 0, len(words)
    while start < end and words[start] in _ADDRESS_FRAME:
        start += 1
    while end > start and words[end - 1] in _ADDRESS_FRAME:
        end -= 1
    core = tuple(words[start:end])
    if not core:
        return False
    return core in names or (len(core) == 1 and (core[0] in _ADDRESS_NOUNS or core[0] in _ADDRESS_ADJECTIVES))


def _glued_address(words: Sequence[str], names: frozenset[tuple[str, ...]], at_start: bool) -> int:
    """How many words at the start (or end) of a clause call her without a comma
    ("Мія молодець", "як ти сонечко"); never the whole clause."""
    for form in sorted(names, key=len, reverse=True):
        size = len(form)
        if size < len(words) and tuple(words[:size] if at_start else words[-size:]) == form:
            return size
    edge = words[0] if at_start else words[-1]
    return 1 if len(words) > 1 and edge in _ADDRESS_NOUNS else 0


def _without_address(clauses: list[list[str]], names: frozenset[tuple[str, ...]]) -> list[str]:
    """The words of the message without the address: "Міє, будь тихо" -> "будь тихо",
    "Як ти, сонечко?" -> "як ти", "Мія молодець" -> "молодець", "Хм, дай подумати" ->
    "дай подумати".  Something always remains: "Міє!" stays "міє"."""
    clauses = [list(clause) for clause in clauses]
    while True:
        if len(clauses) > 1 and len(clauses[0]) == 1 and clauses[0][0] in _OPENERS:
            del clauses[0]
            continue
        kept = [clause for clause in clauses if not _is_address(clause, names)]
        if kept and len(kept) < len(clauses):
            clauses = kept
            continue
        if size := _glued_address(clauses[0], names, at_start=True):
            del clauses[0][:size]
            continue
        if size := _glued_address(clauses[-1], names, at_start=False):
            del clauses[-1][-size:]
            continue
        return [word for clause in clauses for word in clause]


